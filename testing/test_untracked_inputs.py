from tide_tooling import TIDE, node, pipeline
from tide_tooling.tooling_core.engine.classes import DataRef


def test_nested_dependency_keeps_whole_untracked_input_and_child_dependency(capsys):
    @node(targets=["global:source"])
    def source():
        return {"value": 1}

    @node(targets=["global:direct"])
    def direct(value):
        return value

    @node(targets=["global:nested"])
    def nested(value):
        return value

    @pipeline
    def flow():
        value = source()
        direct(value)
        nested([value, {"plain": 2}])

    trace = TIDE().ocean.run_pipeline(flow, mode="sequential")
    direct_record = next(record for record in trace.log if record.func_name == "direct")
    nested_record = next(record for record in trace.log if record.func_name == "nested")

    assert not any(dependency.dep.is_autogenerated for dependency in direct_record.deps)
    assert [dependency.input_path for dependency in nested_record.deps] == [(0, 0), (0,)]

    untracked = next(dependency for dependency in nested_record.deps if dependency.dep.is_autogenerated)
    assert untracked.producer_actor.source_actor == "TIDE: External"
    assert untracked.resolved_value == [{"value": 1}, {"plain": 2}]

    shown = trace.show(color=False)
    capsys.readouterr()
    shown_undeclared = trace.show(color=False, show_undeclared=True)
    capsys.readouterr()

    assert "__untracked__" not in shown
    assert "used: list as an undeclared_input" in shown
    assert "TIDE: External" not in shown
    assert "3 executions shown" in shown
    assert "__untracked__" in shown_undeclared
    assert "as an undeclared_input" not in shown_undeclared
    assert "TIDE: External" in shown_undeclared
    assert "4 executions shown" in shown_undeclared
    assert f"{direct_record.seq_id}: direct" in shown
    assert f"{nested_record.seq_id}: nested" in shown

    expected_inputs = {
        "args": ([{"value": 1}, {"plain": 2}],),
        "kwargs": {},
        "p_args": (),
        "p_kwargs": {},
        "k_args": (),
        "k_kwargs": {},
    }
    inputs = trace.inputs_of(nested_record.seq_id)
    output = trace.output_of(nested_record.exec_id)

    assert inputs.inputs == expected_inputs
    assert inputs.args == expected_inputs["args"]
    assert inputs.kwargs == expected_inputs["kwargs"]
    assert inputs.p_args == expected_inputs["p_args"]
    assert inputs.p_kwargs == expected_inputs["p_kwargs"]
    assert inputs.k_args == expected_inputs["k_args"]
    assert inputs.k_kwargs == expected_inputs["k_kwargs"]
    assert inputs.output == [{"value": 1}, {"plain": 2}]
    assert inputs.to_dict() == {
        "exec_id": nested_record.exec_id,
        "seq_id": nested_record.seq_id,
        "inputs": {
            "args": [[{"value": 1}, {"plain": 2}]],
            "kwargs": {},
            "p_args": [],
            "p_kwargs": {},
            "k_args": [],
            "k_kwargs": {},
        },
    }
    assert output.output == [{"value": 1}, {"plain": 2}]
    assert output.args == expected_inputs["args"]
    assert output.to_dict() == {
        "exec_id": nested_record.exec_id,
        "seq_id": nested_record.seq_id,
        "output": [{"value": 1}, {"plain": 2}],
    }

    shown_inputs = inputs.show(color=False)
    capsys.readouterr()
    shown_output = output.show(color=False)
    capsys.readouterr()

    assert "INPUTS OF EXEC_RECORD" in shown_inputs
    assert "args: tuple" in shown_inputs
    assert "kwargs:" not in shown_inputs
    assert "OUTPUT OF EXEC_RECORD" in shown_output
    assert "output: list" in shown_output

    investigated = trace.investigate(
        nested_record.seq_id,
        grouped=False,
    )
    investigated_dict = investigated.to_dict()
    investigated_show = investigated.show(color=False)
    capsys.readouterr()

    assert investigated_dict["inputs"] == {"args": "tuple"}
    assert investigated_dict["output"] == "list"
    assert "INPUTS:" in investigated_show
    assert "args: tuple" in investigated_show
    assert repr(expected_inputs["args"]) not in investigated_show
    assert "OUTPUT:" in investigated_show
    assert "output: list" in investigated_show


def test_autogenerated_reference_classifier_is_store_explicit():
    assert DataRef("value", "__untracked__").is_autogenerated is True
    assert DataRef("value", "__untracked___7").is_autogenerated is True
    assert DataRef("value", "global").is_autogenerated is False


def test_injection_inputs_follow_the_same_dataref_or_untracked_rule():
    @node(
        args=lambda value: (value,),
        p_args=(2,),
        targets=["global:result"],
    )
    def consume(value):
        return value

    @pipeline
    def flow():
        consume()

    trace = TIDE().ocean.run_pipeline(flow, mode="sequential")
    consumer = next(record for record in trace.log if record.func_name == "consume")

    assert any(
        dependency.associated_input[0] == "p_args" and dependency.dep.is_autogenerated
        for dependency in consumer.deps
    )


def test_inputs_outputs_of_combines_views_and_can_show_raw_inputs(capsys):
    tide = TIDE()
    tide.event("seed", writes={"global:seed": 2})
    tide.exec(
        lambda value: value + 1,
        args=["@global:seed"],
        writes="result",
    )
    trace = tide.trace()
    execution = next(record for record in trace.log if record.func_name == "<lambda>")
    values = trace.inputs_outputs_of(execution.exec_id)

    assert values.args == (2,)
    assert values.output == 3
    assert values.to_dict()["inputs"]["args"] == [2]
    assert values.to_dict(raw=True)["inputs"]["args"] == ["@global:seed"]
    assert values.to_dict()["output"] == 3

    shown = values.show(color=False)
    capsys.readouterr()
    shown_raw = values.show(color=False, raw=True)
    capsys.readouterr()

    assert "INPUTS + OUTPUT OF EXEC_RECORD" in shown
    assert "    (2,)" in shown
    assert "    ('@global:seed',)" in shown_raw
    assert "output: int" in shown_raw
